/**
 * Generates `src/data/rf-profile.json` from the profile's own membership list.
 *
 * The list lives in `packages/core/scripts/rf-components.mjs` and is what
 * `build-rf-essentials.mjs` compiles. The docs cannot import it directly —
 * it sits outside the Astro root and Vite will not resolve it — so it is
 * emitted here as data, on every build, which keeps the guarantee that
 * matters: the page renders exactly what ships, or the build regenerates it.
 *
 * Same rule as api.json/contrast.json — never hand-edit the output.
 */
import { writeFile } from 'node:fs/promises';
import { RF_COMPONENTS } from '../../../packages/core/scripts/rf-components.mjs';

/** Page slugs differ from CSS dirs for a few (alerts, state-patterns, form). */
const PAGE = {
  'checkbox-radio': 'form', 'form-field': 'form', 'form-section': 'form',
  input: 'form', select: 'form', state: 'state-patterns', alert: 'alerts',
};

const components = [...new Set(RF_COMPONENTS.map((p) => p.split('/')[1]))]
  .map((name) => ({ name, href: `/components/${PAGE[name] ?? name}` }));

await writeFile(
  new URL('../src/data/rf-profile.json', import.meta.url),
  JSON.stringify({ $comment: 'GENERATED by scripts/gen-rf-profile.mjs from packages/core/scripts/rf-components.mjs — never hand-edit.', count: components.length, components }, null, 2) + '\n',
);
console.log(`rf-profile.json generated — ${components.length} component(s) in the rf-essentials profile`);
